    create table aircraft_certification (
        airport_id bigint not null,
        id bigint generated by default as identity,
        aircraft_model_name varchar(255) not null,
        primary key (id),
        unique (airport_id, aircraft_model_name)
    );

    create table airport (
        iata_code varchar(3) not null unique,
        latitude float(53) not null,
        longitude float(53) not null,
        id bigint generated by default as identity,
        version bigint,
        city varchar(255) not null,
        country varchar(255) not null,
        name varchar(255) not null,
        operational_hours varchar(255),
        region varchar(255),
        status varchar(255) not null,
        timezone varchar(255) not null,
        primary key (id)
    );

    create table airport_contacts (
        airport_id bigint not null,
        contact_value varchar(255) not null,
        description varchar(255),
        type varchar(255) not null
    );

    create table airport_gates (
        airport_id bigint not null,
        identifier varchar(255)
    );

    create table airport_photos (
        photo_index integer not null,
        airport_id bigint not null,
        photo_content_type varchar(255),
        photo blob,
        primary key (photo_index, airport_id)
    );

    create table airport_runways (
        length integer not null,
        airport_id bigint not null,
        name varchar(255) not null,
        orientation varchar(255) not null
    );

    create table airport_services (
        airport_id bigint not null,
        description varchar(255)
    );

    create table airport_terminals (
        airport_id bigint not null,
        name varchar(255)
    );

    create table flight_copies (
        destination_code varchar(3) not null,
        origin_code varchar(3) not null,
        arrival_date_time timestamp(6) with time zone not null,
        departure_date_time timestamp(6) with time zone not null,
        version bigint not null,
        aircraft_registration varchar(255) not null,
        id varchar(255) not null,
        status varchar(255) not null,
        primary key (id)
    );

    create table replica_state (
        deleted boolean not null,
        stamp bigint not null,
        entity_key varchar(500) not null,
        id varchar(600) not null,
        home varchar(255),
        stamp_node varchar(255),
        type varchar(255) not null,
        primary key (id)
    );

    create table replication_outbox (
        attempts integer not null,
        created_at timestamp(6) with time zone not null,
        id bigint generated by default as identity,
        next_attempt_at timestamp(6) with time zone not null,
        last_error varchar(500),
        path varchar(1000) not null,
        method varchar(255) not null,
        target_node varchar(255) not null,
        body clob,
        primary key (id)
    );

    create table route (
        destination_iata_code varchar(3) not null,
        estimated_flight_time integer not null,
        minimum_capacity integer not null,
        minimum_range float(53) not null,
        origin_iata_code varchar(3) not null,
        id bigint generated by default as identity,
        version bigint,
        status enum ('ACTIVE','INACTIVE','SUSPENDED') not null,
        primary key (id)
    );

    create table route_history (
        changed_at timestamp(6) not null,
        id bigint generated by default as identity,
        route_id bigint not null,
        change_description varchar(255) not null,
        changed_by varchar(255),
        primary key (id)
    );

    create index idx_flight_copies_route
       on flight_copies (origin_code, destination_code);

