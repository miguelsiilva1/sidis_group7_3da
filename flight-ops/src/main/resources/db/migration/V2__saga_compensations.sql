-- Compensations of the flight scheduling Saga that failed over the network,
-- repeated by a scheduled task until the other service accepts them.

    create table saga_compensation (
        id bigint generated by default as identity,
        flight_id varchar(255) not null,
        target_service varchar(50) not null,
        departure_date_time timestamp(6) with time zone not null,
        arrival_date_time timestamp(6) with time zone not null,
        status varchar(50) not null,
        origin_iata_code varchar(3) not null,
        destination_iata_code varchar(3) not null,
        aircraft_registration varchar(255) not null,
        version bigint not null,
        attempts integer not null,
        created_at timestamp(6) with time zone not null,
        last_error varchar(500),
        primary key (id)
    );
