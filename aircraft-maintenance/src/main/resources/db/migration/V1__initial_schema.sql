-- Structure of the aircraft-maintenance database when it moved to Flyway (2026-10-18), as Hibernate created it.
-- Never edit this file: every later change goes in a new file, V2__..., V3__..., applied once
-- and in order on every replica. Databases that existed before Flyway skip this file (baseline).

    create table aircraft_features (
        aircraft_id bigint not null,
        feature varchar(255)
    );

    create table aircraft_models (
        cruising_speed float(53) not null,
        fuel_capacity float(53) not null,
        max_range float(53) not null,
        maximum_seating_capacity integer not null,
        id bigint generated by default as identity,
        image_content_type varchar(255),
        model_name varchar(255) not null unique,
        image blob,
        manufacturer enum ('AIRBUS','ATR','BOEING','BOMBARDIER','COMAC','EMBRAER','MITSUBISHI','SUKHOI') not null,
        primary key (id)
    );

    create table aircrafts (
        manufacturing_date date not null,
        operational_range float(53) not null,
        seat_capacity integer not null,
        id bigint generated by default as identity,
        model_id bigint,
        version bigint,
        registration_number varchar(255) not null unique,
        status varchar(255) not null,
        primary key (id)
    );

    create table flight_copies (
        destination_code varchar(3) not null,
        origin_code varchar(3) not null,
        arrival_date_time timestamp(6) with time zone not null,
        departure_date_time timestamp(6) with time zone not null,
        version bigint not null,
        aircraft_registration varchar(255) not null,
        id varchar(255) not null,
        status varchar(255) not null,
        primary key (id)
    );

    create table maintenance_part (
        minimum_threshold integer not null,
        stock_quantity integer not null,
        id bigint generated by default as identity,
        description varchar(255),
        name varchar(255) not null,
        part_number varchar(255) not null,
        component enum ('AIRFRAME','AVIONICS','ENGINE','EXTERIOR','INTERIOR') not null,
        primary key (id)
    );

    create table maintenance_record (
        cost numeric(15,2) not null,
        expected_duration integer not null,
        completed_at timestamp(6),
        id bigint generated by default as identity,
        start_date timestamp(6) not null,
        template_maintenance_id bigint,
        version bigint,
        record_id uuid not null unique,
        aircraft_registration varchar(255) not null,
        description varchar(255) not null,
        notes varchar(255),
        status enum ('CANCELED','COMPLETED','IN_PROGRESS','PLANNED') not null,
        primary key (id)
    );

    create table maintenance_record_components (
        maintenance_record_id bigint not null,
        component enum ('AIRFRAME','AVIONICS','ENGINE','EXTERIOR','INTERIOR') not null,
        primary key (maintenance_record_id, component)
    );

    create table maintenance_record_parts (
        part_id bigint not null,
        record_id bigint not null
    );

    create table maintenance_template (
        interval_days integer not null,
        interval_flight_hours integer not null,
        maintenance_id bigint generated by default as identity,
        name varchar(255) not null,
        template_type enum ('INSPECTION','MODIFICATION','OVERHAUL','SCHEDULED_MAINTENANCE') not null,
        primary key (maintenance_id)
    );

    create table maintenance_template_models (
        template_id bigint not null,
        model_name varchar(255)
    );

    create table maintenance_template_jpa_entity_checklist (
        maintenance_template_jpa_entity_maintenance_id bigint not null,
        checklist varchar(255) not null
    );

    create table replica_state (
        deleted boolean not null,
        stamp bigint not null,
        entity_key varchar(500) not null,
        id varchar(600) not null,
        home varchar(255),
        stamp_node varchar(255),
        type varchar(255) not null,
        primary key (id)
    );

    create table replication_outbox (
        attempts integer not null,
        created_at timestamp(6) with time zone not null,
        id bigint generated by default as identity,
        next_attempt_at timestamp(6) with time zone not null,
        last_error varchar(500),
        path varchar(1000) not null,
        method varchar(255) not null,
        target_node varchar(255) not null,
        body clob,
        primary key (id)
    );

    create index idx_flight_copies_aircraft
       on flight_copies (aircraft_registration);

